typedef struct {
    bool done;
    uint64_t count;
    double secs;
} UnitResult;

static UnitResult *results;           /* indexed by x*nR + y                 */
static FILE *ckptFile;
static char ckptPath[4096];
static pthread_mutex_t lock = PTHREAD_MUTEX_INITIALIZER;

static void ckpt_header(char *buf, size_t sz, bool useSym)
{
    snprintf(buf, sz, "A253316-checkpoint v1 n=%d lines=%d units=%d sym=%d", n, nR, nUnits, useSym ? 1 : 0);
}

/* open (creating if needed) and lock the checkpoint, then load finished units */
static int ckpt_init(bool useSym)
{
    char want[256];
    ckpt_header(want, sizeof want, useSym);
    ckptFile = fopen(ckptPath, "a+");
    if (!ckptFile) die("cannot open checkpoint %s: %s", ckptPath, strerror(errno));
    if (flock(fileno(ckptFile), LOCK_EX | LOCK_NB) != 0)
        die("checkpoint %s is locked by another running instance", ckptPath);
    rewind(ckptFile);
    char line[512];
    int loaded = 0;
    bool haveHeader = false, endsWithNewline = true;
    while (fgets(line, sizeof line, ckptFile)) {
        size_t len = strlen(line);
        endsWithNewline = len > 0 && line[len - 1] == '\n';
        if (!haveHeader) {
            line[strcspn(line, "\r\n")] = 0;
            if (strcmp(line, want) != 0)
                die("checkpoint %s belongs to a different run:\n  file: %s\n  want: %s", ckptPath, line, want);
            haveHeader = true;
            continue;
        }
        if (line[0] != 'U' || !endsWithNewline) continue;     /* comment or torn line */
        int x, y, wgt;
        char cnt[64];
        double secs;
        if (sscanf(line, "U %d %d %d %63s %lf", &x, &y, &wgt, cnt, &secs) != 5) continue;
        u128 c;
        if (x < 0 || x >= nR || y < 0 || y >= nR || !parse_u128(cnt, &c)) continue;
        UnitResult *r = &results[(size_t)x * nR + y];
        if (!r->done) loaded++;
        r->done = true;
        r->count = (uint64_t)c;
        r->secs = secs;
    }
    if (!haveHeader) {
        fprintf(ckptFile, "%s\n", want);
        fprintf(ckptFile, "# U <x> <y> <orbit weight> <count for seam (x,y)> <seconds>\n");
    } else if (!endsWithNewline) {
        fprintf(ckptFile, "\n");                             /* isolate a torn last line */
    }
    fflush(ckptFile);
    fsync(fileno(ckptFile));
    return loaded;
}

static void ckpt_append(const Unit *u, uint64_t count, double secs)
{
    if (!ckptFile) return;
    fprintf(ckptFile, "U %d %d %d %" PRIu64 " %.3f\n", u->x, u->y, u->weight, count, secs);
    fflush(ckptFile);
    fsync(fileno(ckptFile));
}

