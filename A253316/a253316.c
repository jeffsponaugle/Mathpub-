static int n, N, nR, E;               /* half size, side, #lines, #col pairs */
static uint32_t lineBits[MAXR];       /* valid lines as bit masks            */
static uint32_t lineDense[MAXR];      /* contribution to dense count index   */
static u128 lineAgree[MAXR];          /* bit p: columns of pair p are equal  */
static int lineCompl[MAXR], lineRev[MAXR];
static uint32_t *adjStart;            /* CSR: (a,b) -> c, no column a=b=c    */
static uint8_t *adjList;
static int cntLo, cntHi, cntBase;     /* range of #ones in a half column     */
static uint32_t denseSize, denseSB;   /* base^N, sum_j base^j                */
static int gidShift;                  /* record = eq | rows<<E | gid<<shift  */
static uint64_t gidLimit;
static u128 eqMask;

static int valid_line(uint32_t x, int len, int ones)
{
    if (ones >= 0 && __builtin_popcount(x) != ones) return 0;
    for (int i = 0; i + 2 < len; i++) {
        uint32_t t = (x >> i) & 7;
        if (t == 0 || t == 7) return 0;
    }
    return 1;
}

static void init_tables(int half)
{
    n = half;
    N = 2 * n;
    uint32_t mask = (1u << N) - 1;
    static int idx[1 << MAXC];

    nR = 0;
    for (uint32_t x = 0; x <= mask; x++) {
        idx[x] = -1;
        if (valid_line(x, N, n)) { idx[x] = nR; lineBits[nR++] = x; }
    }
    if (nR > MAXR) die("too many lines");

    /* range of one-counts in an n-long piece of a column with no 000/111 */
    cntLo = n; cntHi = 0;
    for (uint32_t x = 0; x < (1u << n); x++)
        if (valid_line(x, n, -1)) {
            int c = __builtin_popcount(x);
            if (c < cntLo) cntLo = c;
            if (c > cntHi) cntHi = c;
        }
    cntBase = cntHi - cntLo + 1;
    denseSB = 0;
    uint64_t pw = 1;
    for (int j = 0; j < N; j++) { denseSB += (uint32_t)pw; pw *= (uint64_t)cntBase; }
    if (pw > (1u << 30)) die("dense index too large");
    denseSize = (uint32_t)pw;

    E = N * (N - 1) / 2;
    int pj[MAXPAIRS], pk[MAXPAIRS], p = 0;
    for (int j = 0; j < N; j++)
        for (int k = j + 1; k < N; k++) { pj[p] = j; pk[p] = k; p++; }

    for (int r = 0; r < nR; r++) {
        uint32_t x = lineBits[r];
        uint32_t d = 0, pwj = 1;
        for (int j = 0; j < N; j++) { d += ((x >> j) & 1) * pwj; pwj *= (uint32_t)cntBase; }
        lineDense[r] = d;
        u128 ag = 0;
        for (int q = 0; q < E; q++)
            if (((x >> pj[q]) & 1) == ((x >> pk[q]) & 1)) ag |= (u128)1 << q;
        lineAgree[r] = ag;
        lineCompl[r] = idx[~x & mask];
        uint32_t rv = 0;
        for (int j = 0; j < N; j++) if ((x >> j) & 1) rv |= 1u << (N - 1 - j);
        lineRev[r] = idx[rv];
    }

    /* ordered pair (a,b) -> rows c != a,b with no column a=b=c */
    size_t np = (size_t)nR * nR;
    adjStart = xmalloc((np + 1) * sizeof *adjStart);
    size_t tot = 0;
    for (int pass = 0; pass < 2; pass++) {
        tot = 0;
        for (int a = 0; a < nR; a++)
            for (int b = 0; b < nR; b++) {
                if (pass == 0) adjStart[(size_t)a * nR + b] = (uint32_t)tot;
                uint32_t same = ~(lineBits[a] ^ lineBits[b]) & mask;
                for (int c = 0; c < nR; c++) {
                    if (c == a || c == b) continue;
                    if (same & ~(lineBits[b] ^ lineBits[c]) & mask) continue;
                    if (pass == 1) adjList[tot] = (uint8_t)c;
                    tot++;
                }
            }
        if (pass == 0) { adjStart[np] = (uint32_t)tot; adjList = xmalloc(tot + 1); }
    }

    gidShift = E + 8 * (n - 1);
    gidLimit = (128 - gidShift >= 32) ? 0xFFFFFFFEull : ((1ull << (128 - gidShift)) - 1);
    eqMask = (((u128)1) << E) - 1;
}

/* ------------------------------------------------------------------------ */
/* work units: canonical seams under the order-8 symmetry group             */
/* ------------------------------------------------------------------------ */

typedef struct {
    int x, y, weight;
    double estT, estB, cost;
} Unit;

static Unit *units;
static int nUnits;

/* halfCnt[a*nR+b]: #n-row half sequences whose rows next to the seam are
 * (a = second, b = seam row); only local distinctness, so an upper bound */
static double *halfCnt;

static void compute_half_counts(void)
{
    size_t np = (size_t)nR * nR;
    halfCnt = xmalloc(np * sizeof *halfCnt);
    double *nx = xmalloc(np * sizeof *nx);
    if (n == 1) {
        for (size_t i = 0; i < np; i++) halfCnt[i] = 1;   /* unused */
        free(nx);
        return;
    }
    for (int a = 0; a < nR; a++)
        for (int b = 0; b < nR; b++) halfCnt[(size_t)a * nR + b] = (a != b);
    /* f_{L+1}(b,c) = sum_a f_L(a,b); here (a,b) = (older, newer) */
    for (int L = 3; L <= n; L++) {
        memset(nx, 0, np * sizeof *nx);
        for (int a = 0; a < nR; a++)
            for (int b = 0; b < nR; b++) {
                double v = halfCnt[(size_t)a * nR + b];
                if (v == 0) continue;
                size_t p = (size_t)a * nR + b;
                for (uint32_t i = adjStart[p]; i < adjStart[p + 1]; i++)
                    nx[(size_t)b * nR + adjList[i]] += v;
            }
        double *t = halfCnt; halfCnt = nx; nx = t;
    }
    free(nx);
    /* halfCnt[(newest-1)*nR + newest]; by reversal symmetry the number of
     * sequences starting (s, a) equals the number ending (a, s). */
}

static double est_half(int s, uint32_t D)
{
    if (n == 1) return 1;
    uint32_t mask = (1u << N) - 1;
    double t = 0;
    for (int a = 0; a < nR; a++) {
        if (a == s) continue;
        if (~(lineBits[a] ^ lineBits[s]) & D & mask) continue;
        t += halfCnt[(size_t)a * nR + s];
    }
    return t;
}

static int cmp_unit_cost_desc(const void *pa, const void *pb)
{
    const Unit *a = pa, *b = pb;
    if (a->cost > b->cost) return -1;
    if (a->cost < b->cost) return 1;
    if (a->x != b->x) return a->x - b->x;
    return a->y - b->y;
}

static void build_units(bool useSym)
{
    uint32_t mask = (1u << N) - 1;
    units = xmalloc((size_t)nR * nR * sizeof *units);
    nUnits = 0;
    long wsum = 0;
    for (int x = 0; x < nR; x++)
        for (int y = 0; y < nR; y++) {
            if (x == y) continue;
            int w = 1;
            if (useSym) {
                int gx[4] = { x, lineCompl[x], lineRev[x], lineRev[lineCompl[x]] };
                int gy[4] = { y, lineCompl[y], lineRev[y], lineRev[lineCompl[y]] };
                long keys[8], self = (long)x * nR + y;
                int m = 0;
                bool canon = true;
                for (int g = 0; g < 4; g++) {
                    keys[m++] = (long)gx[g] * nR + gy[g];
                    keys[m++] = (long)gy[g] * nR + gx[g];
                }
                for (int i = 0; i < 8; i++) if (keys[i] < self) canon = false;
                if (!canon) continue;
                w = 0;
                for (int i = 0; i < 8; i++) {
                    bool dup = false;
                    for (int j = 0; j < i; j++) if (keys[j] == keys[i]) dup = true;
                    if (!dup) w++;
                }
            }
            Unit *u = &units[nUnits++];
            u->x = x; u->y = y; u->weight = w;
            uint32_t D = ~(lineBits[x] ^ lineBits[y]) & mask;
            u->estT = est_half(x, D);
            u->estB = est_half(y, D);
            /* time model from benchmarks: join ~ estT*estB, enumeration+sort ~ estT+estB */
            u->cost = u->estT * u->estB + 5e6 * (u->estT + u->estB);
            wsum += w;
        }
    if (wsum != (long)nR * (nR - 1)) die("internal: orbit weights sum to %ld", wsum);
}

