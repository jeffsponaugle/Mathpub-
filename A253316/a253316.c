static double now_sec(void)
{
    struct timeval tv;
    gettimeofday(&tv, NULL);
    return tv.tv_sec + tv.tv_usec * 1e-6;
}

static void die(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    fprintf(stderr, "error: ");
    vfprintf(stderr, fmt, ap);
    fprintf(stderr, "\n");
    va_end(ap);
    exit(1);
}

static void *xmalloc(size_t sz)
{
    void *p = malloc(sz ? sz : 1);
    if (!p) die("out of memory allocating %zu bytes", sz);
    return p;
}

static void *xrealloc(void *p, size_t sz)
{
    p = realloc(p, sz ? sz : 1);
    if (!p) die("out of memory reallocating %zu bytes", sz);
    return p;
}

static char *u128_str(u128 v, char *buf) /* buf >= 48 bytes */
{
    char tmp[48];
    int i = 0;
    if (v == 0) tmp[i++] = '0';
    while (v) { tmp[i++] = (char)('0' + (int)(v % 10)); v /= 10; }
    for (int j = 0; j < i; j++) buf[j] = tmp[i - 1 - j];
    buf[i] = 0;
    return buf;
}

static bool parse_u128(const char *s, u128 *out)
{
    u128 v = 0;
    if (!*s) return false;
    for (; *s; s++) {
        if (*s < '0' || *s > '9') return false;
        v = v * 10 + (u128)(*s - '0');
    }
    *out = v;
    return true;
}

static void fmt_dur(double s, char *buf, size_t sz)
{
    if (s < 0 || s != s || s > 1e9) { snprintf(buf, sz, "?"); return; }
    long t = (long)(s + 0.5);
    long d = t / 86400, h = (t / 3600) % 24, m = (t / 60) % 60, x = t % 60;
    if (d) snprintf(buf, sz, "%ldd%02ldh%02ldm", d, h, m);
    else if (h) snprintf(buf, sz, "%ldh%02ldm%02lds", h, m, x);
    else if (m) snprintf(buf, sz, "%ldm%02lds", m, x);
    else snprintf(buf, sz, "%lds", x);
}

