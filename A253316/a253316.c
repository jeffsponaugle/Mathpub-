/*
 * a253316.c -- count 2n x 2n Takuzu grids (OEIS A253316).
 *
 * A Takuzu (Binairo) grid is a 2n x 2n 0/1 matrix in which
 *   (1) every row and every column contains n zeros and n ones,
 *   (2) no row or column contains three consecutive equal entries,
 *   (3) all rows are distinct and all columns are distinct.
 *
 * Known terms, n = 0..5:  1, 2, 72, 4140, 4111116, 48183195384.
 *
 * ALGORITHM
 * ---------
 * Split the grid at the "seam" between rows n and n+1.  For every ordered pair
 * (x, y) of distinct valid lines placed at rows n and n+1:
 *
 *  1. Enumerate every top half T (rows 1..n, ending in x) and every bottom half
 *     B (rows n+1..2n, starting with y) such that the half has distinct valid
 *     rows, no column of the half has three equal consecutive entries, no
 *     column gets three equal entries across the seam, T does not use row y
 *     and B does not use row x.
 *  2. Group halves by their per-column one-counts.  T and B fit together only
 *     if the counts add up to n in every column (a dense mixed-radix index of
 *     the count vector is used as the group key).
 *  3. Inside a group, count the pairs (T, B) that also satisfy
 *       - columns distinct: no column pair (j,k) equal in T *and* equal in B;
 *       - rows distinct:    no row of T (besides x) equal to a row of B.
 *     Every half is summarised by a bit mask of its equal column pairs and its
 *     list of rows ("features").  Two columns can only coincide if they agree
 *     in both seam rows x and y, so the pair masks are restricted to those
 *     pairs up front.  For one side of the group we build a bitset per feature
 *     over the halves that have it; the conflicts of a half on the other side
 *     are the OR of the bitsets of its features (NEON-vectorised), so a
 *     candidate pair costs roughly (6 features / 64) bit operations.
 *     Large groups instead use inclusion-exclusion over the set of shared
 *     rows, with histograms over the distinct pair masks, which is linear in
 *     the number of halves (see join_group_ie).  --join selects the method;
 *     the two were cross-checked on every n = 6 work unit.
 *
 * Seams are reduced by the symmetry group generated by complementing all
 * entries, mirroring left/right and mirroring top/bottom (order 8).  Each
 * canonical seam is an independent work unit; results are appended to a
 * checkpoint file as units complete, so a run can be stopped (Ctrl-C) and
 * resumed later by running the same command again.
 *
 * Supports 1 <= n <= 6 (n = 6, i.e. 12 x 12, is the first unknown term).
 */

