/* straightforward backtracking count, used only by --selftest (n <= 4) */
static uint32_t bfRows[MAXC];
static int bfCnt[MAXC];
static uint64_t bfTotal;

static void brute(int k)
{
    uint32_t mask = (1u << N) - 1;
    if (k == N) {
        for (int i = 0; i < N; i++)
            for (int j = i + 1; j < N; j++) if (bfRows[i] == bfRows[j]) return;
        uint32_t col[MAXC];
        for (int j = 0; j < N; j++) {
            col[j] = 0;
            for (int i = 0; i < N; i++) col[j] |= ((bfRows[i] >> j) & 1u) << i;
        }
        for (int i = 0; i < N; i++)
            for (int j = i + 1; j < N; j++) if (col[i] == col[j]) return;
        bfTotal++;
        return;
    }
    for (int r = 0; r < nR; r++) {
        uint32_t x = lineBits[r];
        if (k >= 2 && (~(bfRows[k - 2] ^ bfRows[k - 1]) & ~(bfRows[k - 1] ^ x) & mask)) continue;
        bool ok = true;
        for (int j = 0; j < N && ok; j++) {
            int c = bfCnt[j] + (int)((x >> j) & 1);
            if (c > n || c + (N - 1 - k) < n) ok = false;
        }
        if (!ok) continue;
        for (int j = 0; j < N; j++) bfCnt[j] += (x >> j) & 1;
        bfRows[k] = x;
        brute(k + 1);
        for (int j = 0; j < N; j++) bfCnt[j] -= (x >> j) & 1;
    }
}

/* full computation for the current tables; returns the total */
static u128 compute(int threads, bool useSym, bool useCkpt, double progressSec, bool isSelftest)
{
    build_units(useSym);
    results = calloc((size_t)nR * nR, sizeof *results);
    if (!results) die("out of memory");

    int loaded = 0;
    if (useCkpt) {
        loaded = ckpt_init(useSym);
    }

    qsort(units, (size_t)nUnits, sizeof *units, cmp_unit_cost_desc);
    order = xmalloc((size_t)nUnits * sizeof *order);
    nOrder = 0;
    costTotal = costDone = 0;
    unitsDone = 0;
    partialSum = 0;
    sessionPairMass = 0;
    for (int i = 0; i < nUnits; i++) {
        costTotal += units[i].cost;
        UnitResult *r = &results[(size_t)units[i].x * nR + units[i].y];
        if (r->done) {
            costDone += units[i].cost;
            unitsDone++;
            partialSum += (u128)r->count * (u128)units[i].weight;
        } else order[nOrder++] = i;
    }
    costDoneStart = costDone;
    atomic_store(&nextOrder, 0);

    if (!quiet && !isSelftest) {
        fprintf(stderr, "A253316: counting %dx%d Takuzu grids (n=%d)\n", N, N, n);
        fprintf(stderr, "  valid lines: %d   seams: %d   work units after symmetry: %d\n",
                nR, nR * (nR - 1), nUnits);
        fprintf(stderr, "  threads: %d   memory budget: %.1f GB   checkpoint: %s\n", threads,
                (double)memBudgetPerThread * threads / 1073741824.0, useCkpt ? ckptPath : "(none)");
        if (loaded) fprintf(stderr, "  resumed: %d units already done (%.2f%% of estimated work)\n",
                            loaded, 100.0 * costDone / costTotal);
    }

    nWorkers = threads;
    workers = xmalloc((size_t)threads * sizeof *workers);
    pthread_t *tids = xmalloc((size_t)threads * sizeof *tids);
    double t0 = now_sec();
    for (int i = 0; i < threads; i++) {
        worker_init(&workers[i], i);
        pthread_attr_t attr;
        pthread_attr_init(&attr);
        pthread_attr_setstacksize(&attr, 16u << 20);
        if (pthread_create(&tids[i], &attr, worker_main, &workers[i]) != 0) die("pthread_create failed");
        pthread_attr_destroy(&attr);
    }

    double lastReport = t0;
    for (;;) {
        bool anyRunning = false;
        /* all workers finished when every pending unit is taken and none is active */
        if (atomic_load(&nextOrder) >= nOrder || stopRequested) {
            anyRunning = false;
            for (int i = 0; i < threads; i++) if (atomic_load(&workers[i].curUnit) >= 0) anyRunning = true;
            if (!anyRunning) break;
        }
        usleep(100000);
        double t = now_sec();
        if (!quiet && !isSelftest && progressSec > 0 && t - lastReport >= progressSec) {
            print_progress(t0, false);
            lastReport = t;
        }
    }
    for (int i = 0; i < threads; i++) pthread_join(tids[i], NULL);
    double el = now_sec() - t0;

    u128 total = 0;
    int missing = 0;
    for (int i = 0; i < nUnits; i++) {
        UnitResult *r = &results[(size_t)units[i].x * nR + units[i].y];
        if (!r->done) { missing++; continue; }
        total += (u128)r->count * (u128)units[i].weight;
    }
    if (!quiet && !isSelftest) {
        print_progress(t0, true);
        char pm[48];
        fprintf(stderr, "  session time %.1fs; candidate pairs examined this session (weighted): %s\n",
                el, u128_str(sessionPairMass, pm));
    }
    for (int i = 0; i < threads; i++) worker_free(&workers[i]);
    free(workers);
    free(tids);
    free(order);
    if (ckptFile) {
        if (missing == 0 && nOrder > 0) {           /* this session finished the run */
            char buf[48];
            fprintf(ckptFile, "# RESULT a(%d) = %s\n", n, u128_str(total, buf));
            fflush(ckptFile);
        }
        fclose(ckptFile);
        ckptFile = NULL;
    }
    free(results);
    results = NULL;
    free(units);
    units = NULL;
    free(halfCnt);
    halfCnt = NULL;
    free(adjStart);
    free(adjList);
    if (missing) {
        if (!quiet && !isSelftest)
            fprintf(stderr, "stopped with %d of %d units remaining; rerun the same command to resume.\n",
                    missing, nUnits);
        return (u128)-1;
    }
    return total;
}

/* time single units (one thread) at spread-out positions of the cost ranking */
static void bench(int samples, int onlyX, int onlyY)
{
    build_units(true);
    qsort(units, (size_t)nUnits, sizeof *units, cmp_unit_cost_desc);
    Worker *w = xmalloc(sizeof *w);
    worker_init(w, 0);
    double costAll = 0;
    for (int i = 0; i < nUnits; i++) costAll += units[i].cost;
    fprintf(stderr, "%5s %4s %4s %2s %10s %10s %8s %8s %6s %14s %13s %6s %6s %7s %8s %10s\n", "rank", "x", "y", "wt",
            "halvesT", "halvesB", "estT", "estB", "groups", "pairMass", "count", "enum", "sort", "join", "total", "sec/cost");
    double sumRatio = 0;
    int cnt = 0;
    for (int s = 0; s < samples; s++) {
        int i;
        if (onlyX >= 0) {
            for (i = 0; i < nUnits; i++) if (units[i].x == onlyX && units[i].y == onlyY) break;
            if (i == nUnits) die("(%d,%d) is not a canonical seam", onlyX, onlyY);
        } else {
            /* geometric spread over ranks */
            double f = samples > 1 ? (double)s / (samples - 1) : 0;
            i = (int)(pow((double)nUnits, f)) - 1;
            if (i < 0) i = 0;
            if (i >= nUnits) i = nUnits - 1;
        }
        const Unit *u = &units[i];
        w->nHalfT = w->nHalfB = w->nGroups = 0;
        w->pairMass = 0;
        w->tEnum = w->tSort = w->tJoin = 0;
        uint64_t c = 0;
        double t0 = now_sec();
        run_unit(w, u, &c);
        double dt = now_sec() - t0;
        char pm[48];
        double ratio = dt / u->cost;
        sumRatio += ratio;
        cnt++;
        fprintf(stderr, "%5d %4d %4d %2d %10" PRIu64 " %10" PRIu64 " %8.3g %8.3g %6" PRIu64 " %14s %13" PRIu64
                " %6.2f %6.2f %7.2f %8.2f %10.3g\n", i, u->x, u->y, u->weight, w->nHalfT, w->nHalfB, u->estT, u->estB,
                w->nGroups, u128_str(w->pairMass, pm), c, w->tEnum, w->tSort, w->tJoin, dt, ratio);
        if (onlyX >= 0) break;
    }
    if (cnt) fprintf(stderr, "mean sec/cost %.3g -> single-thread estimate for all units: %.0f s\n",
                     sumRatio / cnt, sumRatio / cnt * costAll);
    worker_free(w);
    free(w);
}

/* --check-orbits: recount every seam of some random orbits; all must agree */
typedef struct {
    Unit *jobs;
    uint64_t *counts;
    int njobs;
    _Atomic int next;
} JobList;

static void *job_main(void *arg)
{
    void **a = arg;
    JobList *jl = a[0];
    Worker *w = a[1];
    for (;;) {
        int j = atomic_fetch_add(&jl->next, 1);
        if (j >= jl->njobs || stopRequested) break;
        run_unit(w, &jl->jobs[j], &jl->counts[j]);
    }
    return NULL;
}

static int check_orbits(int samples, int threads)
{
    uint32_t mask = (1u << N) - 1;
    build_units(true);
    qsort(units, (size_t)nUnits, sizeof *units, cmp_unit_cost_desc);
    JobList jl = { xmalloc((size_t)samples * 8 * sizeof(Unit)), xmalloc((size_t)samples * 8 * sizeof(uint64_t)), 0, 0 };
    int *owner = xmalloc((size_t)samples * 8 * sizeof(int));
    uint64_t rng = 0x243F6A8885A308D3ull;
    for (int s = 0; s < samples; s++) {
        rng = rng * 6364136223846793005ull + 1442695040888963407ull;
        int ui = nUnits / 4 + (int)((rng >> 33) % (uint64_t)(nUnits - nUnits / 4));
        const Unit *u = &units[ui];
        int x = u->x, y = u->y;
        int gx[4] = { x, lineCompl[x], lineRev[x], lineRev[lineCompl[x]] };
        int gy[4] = { y, lineCompl[y], lineRev[y], lineRev[lineCompl[y]] };
        int img[8][2], m = 0;
        for (int g = 0; g < 4; g++) {
            int cand[2][2] = { { gx[g], gy[g] }, { gy[g], gx[g] } };
            for (int c = 0; c < 2; c++) {
                bool dup = false;
                for (int i = 0; i < m; i++) if (img[i][0] == cand[c][0] && img[i][1] == cand[c][1]) dup = true;
                if (!dup) { img[m][0] = cand[c][0]; img[m][1] = cand[c][1]; m++; }
            }
        }
        if (m != u->weight) die("internal: orbit size %d != weight %d", m, u->weight);
        for (int i = 0; i < m; i++) {
            Unit v = *u;
            v.x = img[i][0];
            v.y = img[i][1];
            uint32_t D = ~(lineBits[v.x] ^ lineBits[v.y]) & mask;
            v.estT = est_half(v.x, D);
            v.estB = est_half(v.y, D);
            owner[jl.njobs] = s;
            jl.jobs[jl.njobs++] = v;
        }
    }
    Worker *ws = xmalloc((size_t)threads * sizeof *ws);
    pthread_t *tids = xmalloc((size_t)threads * sizeof *tids);
    void *args[64][2];
    if (threads > 64) threads = 64;
    for (int i = 0; i < threads; i++) {
        worker_init(&ws[i], i);
        args[i][0] = &jl;
        args[i][1] = &ws[i];
        pthread_create(&tids[i], NULL, job_main, args[i]);
    }
    for (int i = 0; i < threads; i++) pthread_join(tids[i], NULL);
    int bad = 0;
    for (int s = 0, j = 0; s < samples; s++) {
        int j0 = j;
        bool same = true;
        while (j < jl.njobs && owner[j] == s) { if (jl.counts[j] != jl.counts[j0]) same = false; j++; }
        fprintf(stderr, "  orbit of seam (%3d,%3d): %d seams, count %" PRIu64 " %s\n", jl.jobs[j0].x, jl.jobs[j0].y,
                j - j0, jl.counts[j0], same ? "all equal" : "MISMATCH");
        if (!same) {
            bad++;
            for (int k = j0; k < j; k++)
                fprintf(stderr, "      (%3d,%3d) -> %" PRIu64 "\n", jl.jobs[k].x, jl.jobs[k].y, jl.counts[k]);
        }
    }
    for (int i = 0; i < threads; i++) worker_free(&ws[i]);
    fprintf(stderr, bad ? "orbit check FAILED\n" : "orbit check passed\n");
    return bad ? 1 : 0;
}

static int selftest(int threads)
{
    int fails = 0;
    fprintf(stderr, "self-test: brute force (n<=4) and known OEIS terms (n<=5)\n");
    for (int k = 1; k <= 5; k++) {
        init_tables(k);
        compute_half_counts();
        uint64_t bf = 0;
        bool haveBf = false;
        if (k <= 4) {
            bfTotal = 0;
            memset(bfCnt, 0, sizeof bfCnt);
            brute(0);
            bf = bfTotal;
            haveBf = true;
        }
        double t0 = now_sec();
        u128 symRes = compute(threads, true, false, 0, true);
        double t1 = now_sec();
        init_tables(k);
        compute_half_counts();
        u128 fullRes = compute(threads, false, false, 0, true);
        double t2 = now_sec();
        char a[48], b[48], bfs[32];
        u128_str(symRes, a);
        u128_str(fullRes, b);
        if (haveBf) snprintf(bfs, sizeof bfs, "%" PRIu64, bf);
        else snprintf(bfs, sizeof bfs, "-");
        bool ok = strcmp(a, KNOWN[k]) == 0 && strcmp(b, KNOWN[k]) == 0 && (!haveBf || bf == (uint64_t)symRes);
        fprintf(stderr, "  n=%d %2dx%-2d  symmetric %-12s (%6.2fs)  all seams %-12s (%6.2fs)  brute force %-8s  OEIS %-12s %s\n",
                k, 2 * k, 2 * k, a, t1 - t0, b, t2 - t1, bfs, KNOWN[k], ok ? "OK" : "FAIL");
        if (!ok) fails++;
    }
    fprintf(stderr, fails ? "self-test FAILED\n" : "self-test passed\n");
    return fails ? 1 : 0;
}

int main(int argc, char **argv)
{
    int half = 6, threads = ncpu();
    double progressSec = 10, memGB = physmem_gb() * 0.5;
    bool useCkpt = true, useSym = true, doSelftest = false;
    int benchSamples = 0, unitX = -1, unitY = -1, orbitSamples = 0;
    const char *ck = NULL;

    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (!strcmp(a, "-n") && i + 1 < argc) half = atoi(argv[++i]);
        else if (!strcmp(a, "-t") && i + 1 < argc) threads = atoi(argv[++i]);
        else if (!strcmp(a, "-c") && i + 1 < argc) ck = argv[++i];
        else if (!strcmp(a, "-p") && i + 1 < argc) progressSec = atof(argv[++i]);
        else if (!strcmp(a, "-m") && i + 1 < argc) memGB = atof(argv[++i]);
        else if (!strcmp(a, "--no-checkpoint")) useCkpt = false;
        else if (!strcmp(a, "--no-symmetry")) useSym = false;
        else if (!strcmp(a, "--selftest")) doSelftest = true;
        else if (!strcmp(a, "--bench") && i + 1 < argc) benchSamples = atoi(argv[++i]);
        else if (!strcmp(a, "--check-orbits") && i + 1 < argc) orbitSamples = atoi(argv[++i]);
        else if (!strcmp(a, "--ie-min") && i + 1 < argc) ieMin = atof(argv[++i]);
        else if (!strcmp(a, "--join") && i + 1 < argc) {
            const char *m = argv[++i];
            if (!strcmp(m, "auto")) joinMode = JOIN_AUTO;
            else if (!strcmp(m, "bitset")) joinMode = JOIN_BITSET;
            else if (!strcmp(m, "ie")) joinMode = JOIN_IE;
            else if (!strcmp(m, "brute")) joinMode = JOIN_BRUTE;
            else { usage(argv[0]); return 2; }
        }
        else if (!strcmp(a, "--unit") && i + 2 < argc) { unitX = atoi(argv[++i]); unitY = atoi(argv[++i]); }
        else if (!strcmp(a, "-q")) quiet = true;
        else if (!strcmp(a, "-h") || !strcmp(a, "--help")) { usage(argv[0]); return 0; }
        else { usage(argv[0]); return 2; }
    }
    if (threads < 1) threads = 1;
    if (memGB < 0.001) memGB = 0.001;
    memBudgetPerThread = (size_t)(memGB * 1073741824.0 / threads);

    signal(SIGINT, on_signal);
    signal(SIGTERM, on_signal);

    if (doSelftest) return selftest(threads);

    if (half == 0) { printf("a(0) = 1\n"); return 0; }
    if (half < 1 || half > MAXN) die("n must be between 0 and %d", MAXN);
    if (ck) snprintf(ckptPath, sizeof ckptPath, "%s", ck);
    else snprintf(ckptPath, sizeof ckptPath, "a253316_n%d.ckpt", half);

    init_tables(half);
    compute_half_counts();
    if (orbitSamples > 0) return check_orbits(orbitSamples, threads);
    if (benchSamples > 0 || unitX >= 0) {
        bench(unitX >= 0 ? 1 : benchSamples, unitX, unitY);
        return 0;
    }
    u128 res = compute(threads, useSym, useCkpt, progressSec, false);
    if (res == (u128)-1) return 3;
    char buf[48];
    printf("a(%d) = %s\n", half, u128_str(res, buf));
    if (half < NKNOWN) {
        bool ok = strcmp(buf, KNOWN[half]) == 0;
        if (!quiet) fprintf(stderr, "%s known value %s\n", ok ? "matches" : "DOES NOT MATCH", KNOWN[half]);
        return ok ? 0 : 4;
    }
    return 0;
}
