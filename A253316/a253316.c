static int *order;                    /* pending units, largest cost first  */
static int nOrder;
static _Atomic int nextOrder = 0;
static double costTotal, costDoneStart, costDone;
static int unitsDone;
static u128 partialSum;
static u128 sessionPairMass;
static int nWorkers;
static Worker *workers;
static bool quiet = false;

static void *worker_main(void *arg)
{
    Worker *w = arg;
    for (;;) {
        if (stopRequested) break;
        int oi = atomic_fetch_add(&nextOrder, 1);
        if (oi >= nOrder) break;
        int ui = order[oi];
        const Unit *u = &units[ui];
        atomic_store(&w->progPpm, 0);
        atomic_store(&w->curUnit, ui);
        double t0 = now_sec();
        uint64_t cnt = 0;
        u128 massBefore = w->pairMass;
        bool ok = run_unit(w, u, &cnt);
        double dt = now_sec() - t0;
        atomic_store(&w->curUnit, -1);
        if (!ok) break;
        pthread_mutex_lock(&lock);
        UnitResult *r = &results[(size_t)u->x * nR + u->y];
        r->done = true;
        r->count = cnt;
        r->secs = dt;
        ckpt_append(u, cnt, dt);
        costDone += u->cost;
        unitsDone++;
        partialSum += (u128)cnt * (u128)u->weight;
        sessionPairMass += (w->pairMass - massBefore) * (u128)u->weight;
        pthread_mutex_unlock(&lock);
    }
    return NULL;
}

static void on_signal(int sig)
{
    (void)sig;
    if (stopRequested) _exit(130);
    stopRequested = 1;
    const char msg[] = "\n[interrupt] finishing checkpoint and stopping (Ctrl-C again to abort immediately)\n";
    ssize_t rc = write(2, msg, sizeof msg - 1);
    (void)rc;
}

static void print_progress(double t0, bool final)
{
    pthread_mutex_lock(&lock);
    double cd = costDone;
    int ud = unitsDone;
    u128 ps = partialSum;
    pthread_mutex_unlock(&lock);
    double inprog = 0;
    int active = 0;
    for (int i = 0; i < nWorkers; i++) {
        int ui = atomic_load(&workers[i].curUnit);
        if (ui >= 0) {
            active++;
            inprog += units[ui].cost * (double)atomic_load(&workers[i].progPpm) / 1e6;
        }
    }
    double el = now_sec() - t0;
    double doneNow = cd + inprog;
    double frac = costTotal > 0 ? doneNow / costTotal : 1;
    double sess = doneNow - costDoneStart;
    double eta = sess > 0 ? (costTotal - doneNow) * el / sess : -1;
    char e1[32], e2[32], ps_s[48];
    fmt_dur(el, e1, sizeof e1);
    fmt_dur(eta, e2, sizeof e2);
    u128_str(ps, ps_s);
    time_t tt = time(NULL);
    struct tm tmv;
    localtime_r(&tt, &tmv);
    char ts[32];
    strftime(ts, sizeof ts, "%H:%M:%S", &tmv);
    char etaAt[32] = "";
    if (eta >= 0 && !final) {
        time_t fin = tt + (time_t)eta;
        struct tm tf;
        localtime_r(&fin, &tf);
        strftime(etaAt, sizeof etaAt, " (~%a %H:%M)", &tf);
    }
    fprintf(stderr, "[%s] units %d/%d  work %6.2f%%  active %d  elapsed %s  ETA %s%s  partial %s\n",
            ts, ud, nUnits, 100.0 * frac, active, e1, final ? "-" : e2, etaAt, ps_s);
}

