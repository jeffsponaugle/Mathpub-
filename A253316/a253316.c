typedef struct {
    /* halves of the current pass */
    u128 *T, *B;
    size_t Tn, Tcap, Bn, Bcap;
    /* groups */
    uint32_t *gidOf;            /* dense count index -> gid (NO_GID)       */
    uint32_t *gidIdx;           /* gid -> dense index                       */
    uint32_t *cntT, *cntB;
    size_t *startT, *startB, *nextPos;
    size_t gcap;
    uint32_t ng;
    /* bitset join scratch */
    uint64_t *bits;
    size_t bitsCap;
    int16_t featSlot[MAXFEAT];
    int usedFeat[MAXFEAT];
    /* inclusion-exclusion join scratch */
    u128 *mmKey;                /* mask -> id hash map (stamped entries)     */
    uint32_t *mmVal, *mmStamp, mmCur;
    size_t mmCap;
    uint32_t *idT, *idB, *ident;/* mask id per record, identity index list  */
    u128 *maskT, *maskB;        /* distinct masks of each side              */
    size_t idCap;
    uint8_t *dj;                /* dj[a*dB+b]: masks a, b disjoint          */
    size_t djCap;
    uint32_t dT, dB;
    uint32_t *hx, *hy, *touchX, *touchY;  /* histograms, kept zero         */
    uint32_t *lst[2][MAXN];     /* per-depth partition lists                */
    size_t lstCap;
    uint32_t ieCnt[MAXN][2][MAXR], ieOff[MAXN][2][MAXR];
    uint8_t ieTouch[MAXN][MAXR];
    uint64_t ieGroups, bsGroups;
    /* DFS state */
    int h[MAXN];
    uint8_t used[MAXR];
    uint8_t lvl1[MAXR];
    int nlvl1;
    int side, K, pass;
    bool overflow;
    /* statistics */
    u128 pairMass;              /* candidate pairs (count vectors match)    */
    uint64_t nHalfT, nHalfB, nGroups;
    double tEnum, tSort, tJoin;
    /* progress, read by the monitor thread */
    _Atomic int curUnit;        /* index into units[], -1 when idle         */
    _Atomic uint64_t progPpm;   /* completed fraction of the unit, x1e6     */
    int id;
} Worker;

static void worker_init(Worker *w, int id)
{
    memset(w, 0, sizeof *w);
    w->id = id;
    w->gidOf = xmalloc((size_t)denseSize * sizeof *w->gidOf);
    for (uint32_t i = 0; i < denseSize; i++) w->gidOf[i] = NO_GID;
    w->gcap = 1024;
    w->gidIdx = xmalloc(w->gcap * sizeof *w->gidIdx);
    w->cntT = xmalloc(w->gcap * sizeof *w->cntT);
    w->cntB = xmalloc(w->gcap * sizeof *w->cntB);
    w->startT = xmalloc((w->gcap + 1) * sizeof *w->startT);
    w->startB = xmalloc((w->gcap + 1) * sizeof *w->startB);
    w->nextPos = xmalloc((w->gcap + 1) * sizeof *w->nextPos);
    for (int f = 0; f < MAXFEAT; f++) w->featSlot[f] = -1;
    atomic_store(&w->curUnit, -1);
}

static void worker_free(Worker *w)
{
    free(w->T); free(w->B); free(w->gidOf); free(w->gidIdx); free(w->cntT); free(w->cntB);
    free(w->startT); free(w->startB); free(w->nextPos); free(w->bits);
    free(w->mmKey); free(w->mmVal); free(w->mmStamp); free(w->idT); free(w->idB); free(w->ident);
    free(w->maskT); free(w->maskB); free(w->dj); free(w->hx); free(w->hy); free(w->touchX); free(w->touchY);
    for (int d = 0; d < MAXN; d++) { free(w->lst[0][d]); free(w->lst[1][d]); }
}

static void grow_groups(Worker *w)
{
    size_t nc = w->gcap * 2;
    w->gidIdx = xrealloc(w->gidIdx, nc * sizeof *w->gidIdx);
    w->cntT = xrealloc(w->cntT, nc * sizeof *w->cntT);
    w->cntB = xrealloc(w->cntB, nc * sizeof *w->cntB);
    w->startT = xrealloc(w->startT, (nc + 1) * sizeof *w->startT);
    w->startB = xrealloc(w->startB, (nc + 1) * sizeof *w->startB);
    w->nextPos = xrealloc(w->nextPos, (nc + 1) * sizeof *w->nextPos);
    w->gcap = nc;
}

static inline uint32_t pass_of(uint32_t idx, int K)
{
    return (uint32_t)((((uint64_t)idx * 0x9E3779B97F4A7C15ull) >> 32) % (uint64_t)K);
}

/* ------------------------------------------------------------------------ */
/* half enumeration                                                         */
/* ------------------------------------------------------------------------ */

static inline void emit_half(Worker *w, uint32_t dsum, u128 agree)
{
    uint32_t idx;
    if (w->side == 0) idx = dsum - (uint32_t)cntLo * denseSB;
    else              idx = (uint32_t)(n - cntLo) * denseSB - dsum;   /* complementary key */
    if (w->K > 1 && pass_of(idx, w->K) != (uint32_t)w->pass) return;
    uint32_t g = w->gidOf[idx];
    if (w->side == 0) {
        if (g == NO_GID) {
            if (w->ng >= gidLimit) { w->overflow = true; return; }
            if (w->ng >= w->gcap) grow_groups(w);
            g = w->ng++;
            w->gidOf[idx] = g;
            w->gidIdx[g] = idx;
            w->cntT[g] = 0;
            w->cntB[g] = 0;
        }
        w->cntT[g]++;
    } else {
        if (g == NO_GID) return;
        w->cntB[g]++;
    }
    uint64_t rows = 0;
    for (int i = 1; i < n; i++) rows |= (uint64_t)w->h[i] << (8 * (i - 1));
    u128 rec = agree | ((u128)rows << E) | ((u128)g << gidShift);
    if (w->side == 0) {
        if (w->Tn == w->Tcap) { w->Tcap = w->Tcap * 3 / 2 + 1024; w->T = xrealloc(w->T, w->Tcap * sizeof(u128)); }
        w->T[w->Tn++] = rec;
    } else {
        if (w->Bn == w->Bcap) { w->Bcap = w->Bcap * 3 / 2 + 1024; w->B = xrealloc(w->B, w->Bcap * sizeof(u128)); }
        w->B[w->Bn++] = rec;
    }
}

static void dfs_half(Worker *w, int k, uint32_t dsum, u128 agree)
{
    if (k == n) { emit_half(w, dsum, agree); return; }
    const uint8_t *lst;
    uint32_t cnt;
    if (k == 1) { lst = w->lvl1; cnt = (uint32_t)w->nlvl1; }
    else {
        size_t p = (size_t)w->h[k - 2] * nR + w->h[k - 1];
        lst = adjList + adjStart[p];
        cnt = adjStart[p + 1] - adjStart[p];
    }
    for (uint32_t i = 0; i < cnt; i++) {
        int r = lst[i];
        if (w->used[r]) continue;
        w->used[r] = 1;
        w->h[k] = r;
        dfs_half(w, k + 1, dsum + lineDense[r], agree & lineAgree[r]);
        w->used[r] = 0;
    }
}

/* enumerate halves whose seam row is s, avoiding row 'forbid' */
static void enum_side(Worker *w, int side, int s, int forbid, uint32_t D)
{
    uint32_t mask = (1u << N) - 1;
    w->side = side;
    w->nlvl1 = 0;
    for (int a = 0; a < nR; a++) {
        if (a == s || a == forbid) continue;
        if (~(lineBits[a] ^ lineBits[s]) & D & mask) continue;   /* seam triple */
        w->lvl1[w->nlvl1++] = (uint8_t)a;
    }
    memset(w->used, 0, sizeof w->used);
    w->used[s] = 1;
    w->used[forbid] = 1;
    w->h[0] = s;
    /* a column pair can only clash if it is equal in both halves, hence equal
     * in both seam rows: keep only pairs on which the other seam row agrees */
    dfs_half(w, 1, lineDense[s], lineAgree[s] & lineAgree[forbid]);
}

/* ------------------------------------------------------------------------ */
/* grouping (in-place counting sort by gid)                                 */
/* ------------------------------------------------------------------------ */

#define REC_GID(r) ((uint32_t)((r) >> gidShift))

static void sort_by_gid(u128 *a, uint32_t ng, const uint32_t *cnt, size_t *start, size_t *next)
{
    start[0] = 0;
    for (uint32_t g = 0; g < ng; g++) start[g + 1] = start[g] + cnt[g];
    for (uint32_t g = 0; g < ng; g++) next[g] = start[g];
    for (uint32_t g = 0; g < ng; g++) {
        while (next[g] < start[g + 1]) {
            u128 v = a[next[g]];
            uint32_t gv = REC_GID(v);
            while (gv != g) {
                u128 t = a[next[gv]];
                a[next[gv]++] = v;
                v = t;
                gv = REC_GID(v);
            }
            a[next[g]++] = v;
        }
    }
}

/* ------------------------------------------------------------------------ */
/* counting compatible pairs inside a group                                 */
/* ------------------------------------------------------------------------ */

static inline int rec_features(u128 r, int *feat)
{
    int k = 0;
    u128 eq = r & eqMask;
    uint64_t e0 = (uint64_t)eq, e1 = (uint64_t)(eq >> 64);
    while (e0) { feat[k++] = __builtin_ctzll(e0); e0 &= e0 - 1; }
    while (e1) { feat[k++] = 64 + __builtin_ctzll(e1); e1 &= e1 - 1; }
    uint64_t rows = (uint64_t)(r >> E);
    for (int i = 1; i < n; i++) { feat[k++] = E + (int)(rows & 0xFF); rows >>= 8; }
    return k;
}

/* number of bits set in (ptr[0] | ... | ptr[m-1]) over W words */
static inline uint64_t or_popcount(const uint64_t *const *ptr, int m, size_t W)
{
    uint64_t total = 0;
    size_t wd = 0;
#if defined(__ARM_NEON)
    if (W >= 4) {
        uint16x8_t c0 = vdupq_n_u16(0), c1 = vdupq_n_u16(0);
        for (; wd + 4 <= W; wd += 4) {          /* W <= CHUNK/64: no u16 overflow */
            uint64x2_t v0 = vld1q_u64(ptr[0] + wd), v1 = vld1q_u64(ptr[0] + wd + 2);
            for (int q = 1; q < m; q++) {
                v0 = vorrq_u64(v0, vld1q_u64(ptr[q] + wd));
                v1 = vorrq_u64(v1, vld1q_u64(ptr[q] + wd + 2));
            }
            c0 = vpadalq_u8(c0, vcntq_u8(vreinterpretq_u8_u64(v0)));
            c1 = vpadalq_u8(c1, vcntq_u8(vreinterpretq_u8_u64(v1)));
        }
        total = vaddlvq_u16(c0) + vaddlvq_u16(c1);
    }
#endif
    for (; wd < W; wd++) {
        uint64_t v = ptr[0][wd];
        for (int q = 1; q < m; q++) v |= ptr[q][wd];
        total += (uint64_t)__builtin_popcountll(v);
    }
    return total;
}

/* S: records turned into per-feature bitsets (s <= CHUNK); L: probed records */
static uint64_t join_chunk(Worker *w, const u128 *S, size_t s, const u128 *L, size_t l)
{
    size_t W = (s + 63) >> 6;
    int nslots = 0;
    int feat[MAXPAIRS + MAXN];

    if (w->bitsCap < (size_t)MAXFEAT * W) {
        w->bitsCap = (size_t)MAXFEAT * W;
        free(w->bits);
        w->bits = xmalloc(w->bitsCap * sizeof(uint64_t));
    }
    uint64_t *bits = w->bits;

    for (size_t i = 0; i < s; i++) {
        int k = rec_features(S[i], feat);
        uint64_t bit = 1ull << (i & 63);
        size_t wd = i >> 6;
        for (int q = 0; q < k; q++) {
            int f = feat[q];
            int slot = w->featSlot[f];
            if (slot < 0) {
                slot = nslots++;
                w->featSlot[f] = (int16_t)slot;
                w->usedFeat[slot] = f;
                memset(bits + (size_t)slot * W, 0, W * sizeof(uint64_t));
            }
            bits[(size_t)slot * W + wd] |= bit;
        }
    }

    uint64_t total = 0;
    const uint64_t *ptr[MAXPAIRS + MAXN];
    for (size_t j = 0; j < l; j++) {
        int k = rec_features(L[j], feat), m = 0;
        for (int q = 0; q < k; q++) {
            int slot = w->featSlot[feat[q]];
            if (slot >= 0) ptr[m++] = bits + (size_t)slot * W;
        }
        if (m == 0) { total += s; continue; }
        uint64_t conf;
        if (W == 1) {
            uint64_t v = 0;
            for (int q = 0; q < m; q++) v |= ptr[q][0];
            conf = (uint64_t)__builtin_popcountll(v);
        } else conf = or_popcount(ptr, m, W);
        total += s - conf;
    }

    for (int q = 0; q < nslots; q++) w->featSlot[w->usedFeat[q]] = -1;
    return total;
}

/* reference implementation (--join brute): test every pair directly */
enum { JOIN_AUTO, JOIN_BITSET, JOIN_IE, JOIN_BRUTE };
static int joinMode = JOIN_AUTO;
static double ieMin = 6400;           /* auto: inclusion-exclusion if A*B > ieMin*(A+B) */

static uint64_t join_group_brute(const u128 *T, size_t A, const u128 *B, size_t Bn)
{
    uint64_t total = 0;
    for (size_t i = 0; i < A; i++) {
        uint64_t rs[MAXR / 64] = { 0 };
        uint64_t rows = (uint64_t)(T[i] >> E);
        for (int k = 1; k < n; k++) { int v = (int)(rows & 0xFF); rows >>= 8; rs[v >> 6] |= 1ull << (v & 63); }
        u128 eqT = T[i] & eqMask;
        for (size_t j = 0; j < Bn; j++) {
            if (eqT & B[j] & eqMask) continue;                 /* two equal columns */
            uint64_t rb = (uint64_t)(B[j] >> E);
            bool clash = false;
            for (int k = 1; k < n; k++) {
                int v = (int)(rb & 0xFF);
                rb >>= 8;
                if (rs[v >> 6] >> (v & 63) & 1) clash = true;    /* repeated row */
            }
            if (!clash) total++;
        }
    }
    return total;
}


/* ------------------------------------------------------------------------ */
/* counting compatible pairs, method 2: inclusion-exclusion over shared rows */
/* ------------------------------------------------------------------------ */
/*
 * clean(T,B) = sum over sets R of row values of (-1)^|R| * E(T_R, B_R), where
 * T_R are the halves containing every row of R and E(X,Y) is the number of
 * pairs of X x Y whose equal-column-pair masks are disjoint.  E comes from
 * histograms over the distinct masks of each side and a table of which
 * distinct masks are disjoint.  R is generated in increasing order:
 *     f(X, Y, m) = E(X, Y) - sum_{v > m} f(X_v, Y_v, v),   clean = f(T, B, -1).
 * The cost is linear in the number of halves (times the <= 2^(n-1) subsets
 * of rows they share) instead of proportional to the number of pairs.
 */

#define IE_DIRECT 48                  /* |X|*|Y| at or below: direct pairs    */
#define DJ_MAX    (1u << 24)          /* largest distinct-mask table          */

static inline uint64_t mask_hash(u128 m)
{
    uint64_t h = (uint64_t)m * 0x9E3779B97F4A7C15ull ^ (uint64_t)(m >> 64) * 0xC2B2AE3D27D4EB4Full;
    return h ^ (h >> 31);
}

/* ids[i] = index of the distinct mask of R[i]; returns #distinct masks */
static uint32_t assign_ids(Worker *w, const u128 *R, size_t cnt, uint32_t *ids, u128 *masks)
{
    size_t cap = 64;
    while (cap < 2 * cnt) cap <<= 1;
    if (cap > w->mmCap) {
        free(w->mmKey); free(w->mmVal); free(w->mmStamp);
        w->mmKey = xmalloc(cap * sizeof(u128));
        w->mmVal = xmalloc(cap * sizeof(uint32_t));
        w->mmStamp = calloc(cap, sizeof(uint32_t));
        if (!w->mmStamp) die("out of memory");
        w->mmCap = cap;
        w->mmCur = 0;
    }
    if (++w->mmCur == 0) { memset(w->mmStamp, 0, w->mmCap * sizeof(uint32_t)); w->mmCur = 1; }
    uint32_t cur = w->mmCur, d = 0;
    size_t hm = cap - 1;
    for (size_t i = 0; i < cnt; i++) {
        u128 m = R[i] & eqMask;
        size_t h = mask_hash(m) & hm;
        for (;;) {
            if (w->mmStamp[h] != cur) {
                w->mmStamp[h] = cur;
                w->mmKey[h] = m;
                w->mmVal[h] = d;
                masks[d] = m;
                ids[i] = d++;
                break;
            }
            if (w->mmKey[h] == m) { ids[i] = w->mmVal[h]; break; }
            h = (h + 1) & hm;
        }
    }
    return d;
}

/* pairs of X x Y with disjoint masks (E above) */
static uint64_t ie_eq_clean(Worker *w, const uint32_t *X, size_t nx, const uint32_t *Y, size_t ny)
{
    const uint32_t *idT = w->idT, *idB = w->idB;
    const uint8_t *dj = w->dj;
    uint32_t dB = w->dB, *hx = w->hx, *hy = w->hy;
    size_t tx = 0, ty = 0;
    for (size_t i = 0; i < nx; i++) { uint32_t a = idT[X[i]]; if (hx[a]++ == 0) w->touchX[tx++] = a; }
    for (size_t j = 0; j < ny; j++) { uint32_t b = idB[Y[j]]; if (hy[b]++ == 0) w->touchY[ty++] = b; }
    uint64_t sum = 0;
    for (size_t i = 0; i < tx; i++) {
        uint32_t a = w->touchX[i];
        const uint8_t *row = dj + (size_t)a * dB;
        uint64_t sb = 0;
        for (size_t j = 0; j < ty; j++) { uint32_t b = w->touchY[j]; sb += row[b] ? hy[b] : 0; }
        sum += (uint64_t)hx[a] * sb;
    }
    for (size_t i = 0; i < tx; i++) hx[w->touchX[i]] = 0;
    for (size_t j = 0; j < ty; j++) hy[w->touchY[j]] = 0;
    return sum;
}

/* pairs with disjoint masks and no common row greater than minRow */
static int64_t ie_direct(Worker *w, const u128 *T, const u128 *B, const uint32_t *X, size_t nx,
                         const uint32_t *Y, size_t ny, int minRow)
{
    int64_t cnt = 0;
    for (size_t i = 0; i < nx; i++) {
        uint64_t rs[MAXR / 64] = { 0 };
        uint64_t rows = (uint64_t)(T[X[i]] >> E);
        for (int k = 1; k < n; k++) {
            int v = (int)(rows & 0xFF);
            rows >>= 8;
            if (v > minRow) rs[v >> 6] |= 1ull << (v & 63);
        }
        const uint8_t *row = w->dj + (size_t)w->idT[X[i]] * w->dB;
        for (size_t j = 0; j < ny; j++) {
            if (!row[w->idB[Y[j]]]) continue;
            uint64_t rb = (uint64_t)(B[Y[j]] >> E);
            bool clash = false;
            for (int k = 1; k < n; k++) {
                int v = (int)(rb & 0xFF);
                rb >>= 8;
                if (rs[v >> 6] >> (v & 63) & 1) clash = true;
            }
            cnt += !clash;
        }
    }
    return cnt;
}

static int64_t ie_rec(Worker *w, const u128 *T, const u128 *B, const uint32_t *X, size_t nx,
                      const uint32_t *Y, size_t ny, int minRow, int depth)
{
    if (nx * ny <= IE_DIRECT) return ie_direct(w, T, B, X, nx, Y, ny, minRow);
    int64_t res = (int64_t)ie_eq_clean(w, X, nx, Y, ny);
    if (depth >= n - 1) return res;                 /* every row already shared */
    uint32_t *cx = w->ieCnt[depth][0], *cy = w->ieCnt[depth][1];
    uint32_t *ox = w->ieOff[depth][0], *oy = w->ieOff[depth][1];
    uint8_t *tv = w->ieTouch[depth];
    int ntv = 0;
    for (size_t i = 0; i < nx; i++) {
        uint64_t rows = (uint64_t)(T[X[i]] >> E);
        for (int k = 1; k < n; k++) {
            int v = (int)(rows & 0xFF);
            rows >>= 8;
            if (v > minRow && cx[v]++ == 0 && cy[v] == 0) tv[ntv++] = (uint8_t)v;
        }
    }
    for (size_t j = 0; j < ny; j++) {
        uint64_t rows = (uint64_t)(B[Y[j]] >> E);
        for (int k = 1; k < n; k++) {
            int v = (int)(rows & 0xFF);
            rows >>= 8;
            if (v > minRow && cy[v]++ == 0 && cx[v] == 0) tv[ntv++] = (uint8_t)v;
        }
    }
    uint32_t px = 0, py = 0;
    for (int t = 0; t < ntv; t++) {
        int v = tv[t];
        if (cx[v] && cy[v]) { ox[v] = px; px += cx[v]; oy[v] = py; py += cy[v]; }
    }
    if (px) {
        uint32_t *lx = w->lst[0][depth], *ly = w->lst[1][depth];
        for (size_t i = 0; i < nx; i++) {
            uint64_t rows = (uint64_t)(T[X[i]] >> E);
            for (int k = 1; k < n; k++) {
                int v = (int)(rows & 0xFF);
                rows >>= 8;
                if (v > minRow && cy[v]) lx[ox[v]++] = X[i];
            }
        }
        for (size_t j = 0; j < ny; j++) {
            uint64_t rows = (uint64_t)(B[Y[j]] >> E);
            for (int k = 1; k < n; k++) {
                int v = (int)(rows & 0xFF);
                rows >>= 8;
                if (v > minRow && cx[v]) ly[oy[v]++] = Y[j];
            }
        }
        for (int t = 0; t < ntv; t++) {
            int v = tv[t];
            if (cx[v] && cy[v]) {
                uint32_t sx = ox[v] - cx[v], sy = oy[v] - cy[v];
                res -= ie_rec(w, T, B, lx + sx, cx[v], ly + sy, cy[v], v, depth + 1);
            }
        }
    }
    for (int t = 0; t < ntv; t++) { cx[tv[t]] = 0; cy[tv[t]] = 0; }
    return res;
}

/* returns false if the distinct-mask table would be too large */
static bool join_group_ie(Worker *w, const u128 *T, size_t A, const u128 *B, size_t Bn, uint64_t *out)
{
    size_t need = A > Bn ? A : Bn;
    if (w->idCap < need) {
        free(w->idT); free(w->idB); free(w->ident); free(w->maskT); free(w->maskB);
        free(w->hx); free(w->hy); free(w->touchX); free(w->touchY);
        w->idCap = need + need / 2;
        w->idT = xmalloc(w->idCap * sizeof(uint32_t));
        w->idB = xmalloc(w->idCap * sizeof(uint32_t));
        w->ident = xmalloc(w->idCap * sizeof(uint32_t));
        for (size_t i = 0; i < w->idCap; i++) w->ident[i] = (uint32_t)i;
        w->maskT = xmalloc(w->idCap * sizeof(u128));
        w->maskB = xmalloc(w->idCap * sizeof(u128));
        w->hx = calloc(w->idCap, sizeof(uint32_t));
        w->hy = calloc(w->idCap, sizeof(uint32_t));
        w->touchX = xmalloc(w->idCap * sizeof(uint32_t));
        w->touchY = xmalloc(w->idCap * sizeof(uint32_t));
        if (!w->hx || !w->hy) die("out of memory");
    }
    w->dT = assign_ids(w, T, A, w->idT, w->maskT);
    w->dB = assign_ids(w, B, Bn, w->idB, w->maskB);
    size_t djn = (size_t)w->dT * w->dB;
    if (djn > DJ_MAX) return false;
    if (w->djCap < djn) { free(w->dj); w->djCap = djn + djn / 2; w->dj = xmalloc(w->djCap); }
    for (uint32_t a = 0; a < w->dT; a++) {
        u128 ma = w->maskT[a];
        uint8_t *row = w->dj + (size_t)a * w->dB;
        for (uint32_t b = 0; b < w->dB; b++) row[b] = (ma & w->maskB[b]) == 0;
    }
    size_t lneed = (size_t)(n - 1) * need;
    if (w->lstCap < lneed) {
        w->lstCap = lneed + lneed / 2;
        for (int d = 0; d < MAXN; d++) {
            free(w->lst[0][d]); free(w->lst[1][d]);
            w->lst[0][d] = xmalloc(w->lstCap * sizeof(uint32_t));
            w->lst[1][d] = xmalloc(w->lstCap * sizeof(uint32_t));
        }
    }
    int64_t r = ie_rec(w, T, B, w->ident, A, w->ident, Bn, -1, 0);
    if (r < 0) die("internal: negative inclusion-exclusion count");
    *out = (uint64_t)r;
    return true;
}

static uint64_t join_group(Worker *w, const u128 *T, size_t A, const u128 *B, size_t Bn)
{
    if (joinMode == JOIN_BRUTE) return join_group_brute(T, A, B, Bn);
    /* inclusion-exclusion is linear in A+B, bitsets cost ~ 6*A*B/64 */
    if (joinMode == JOIN_IE || (joinMode == JOIN_AUTO && (double)A * Bn > ieMin * (double)(A + Bn))) {
        uint64_t r;
        if (join_group_ie(w, T, A, B, Bn, &r)) { w->ieGroups++; return r; }
    }
    w->bsGroups++;
    const u128 *S, *L;
    size_t s, l;
    /* bitsets over the side that minimises (#probes) * (#bitset words) */
    if ((uint64_t)A * ((Bn + 63) / 64) <= (uint64_t)Bn * ((A + 63) / 64)) { S = B; s = Bn; L = T; l = A; }
    else { S = T; s = A; L = B; l = Bn; }
    uint64_t total = 0;
    for (size_t c0 = 0; c0 < s; c0 += CHUNK) {
        size_t cs = s - c0 < CHUNK ? s - c0 : CHUNK;
        total += join_chunk(w, S + c0, cs, L, l);
    }
    return total;
}

/* ------------------------------------------------------------------------ */
/* one work unit                                                            */
/* ------------------------------------------------------------------------ */

static volatile sig_atomic_t stopRequested = 0;
static size_t memBudgetPerThread;     /* bytes for half records per thread  */

static void reset_groups(Worker *w)
{
    for (uint32_t g = 0; g < w->ng; g++) w->gidOf[w->gidIdx[g]] = NO_GID;
    w->ng = 0;
    w->Tn = w->Bn = 0;
}

/* returns false if interrupted (result invalid) */
static bool run_unit(Worker *w, const Unit *u, uint64_t *result)
{
    uint32_t mask = (1u << N) - 1;
    uint32_t D = ~(lineBits[u->x] ^ lineBits[u->y]) & mask;
    double need = (u->estT + u->estB) * sizeof(u128) * 1.15;
    int K = (int)(need / (double)memBudgetPerThread) + 1;
    uint64_t total = 0;

    for (int attempt = 0;; attempt++) {
        bool redo = false;
        total = 0;
        for (int pass = 0; pass < K; pass++) {
            w->K = K;
            w->pass = pass;
            w->overflow = false;
            reset_groups(w);
            size_t wantT = (size_t)(u->estT / K * 1.05) + 1024;
            size_t wantB = (size_t)(u->estB / K * 1.05) + 1024;
            if (w->Tcap < wantT) { free(w->T); w->Tcap = wantT; w->T = xmalloc(wantT * sizeof(u128)); }
            if (w->Bcap < wantB) { free(w->B); w->Bcap = wantB; w->B = xmalloc(wantB * sizeof(u128)); }
            double ta = now_sec();
            enum_side(w, 0, u->x, u->y, D);
            if (w->overflow) { redo = true; break; }
            enum_side(w, 1, u->y, u->x, D);
            double tb = now_sec();
            w->tEnum += tb - ta;
            w->nHalfT += w->Tn;
            w->nHalfB += w->Bn;
            w->nGroups += w->ng;

            /* drop tops whose group has no bottom */
            size_t o = 0;
            for (size_t i = 0; i < w->Tn; i++) {
                u128 r = w->T[i];
                if (w->cntB[REC_GID(r)]) w->T[o++] = r;
            }
            w->Tn = o;
            for (uint32_t g = 0; g < w->ng; g++) if (!w->cntB[g]) w->cntT[g] = 0;
            sort_by_gid(w->T, w->ng, w->cntT, w->startT, w->nextPos);
            sort_by_gid(w->B, w->ng, w->cntB, w->startB, w->nextPos);
            double tc = now_sec();
            w->tSort += tc - tb;

            u128 mass = 0, done = 0;
            for (uint32_t g = 0; g < w->ng; g++) mass += (u128)w->cntT[g] * w->cntB[g];
            w->pairMass += mass;
            u128 lastReport = 0;
            for (uint32_t g = 0; g < w->ng; g++) {
                if (!w->cntT[g] || !w->cntB[g]) continue;
                total += join_group(w, w->T + w->startT[g], w->cntT[g], w->B + w->startB[g], w->cntB[g]);
                done += (u128)w->cntT[g] * w->cntB[g];
                if (done - lastReport > (u128)200000000u) {
                    lastReport = done;
                    double f = ((double)pass + (double)done / (double)mass) / K;
                    atomic_store(&w->progPpm, (uint64_t)(f * 1e6));
                    if (stopRequested) return false;
                }
            }
            w->tJoin += now_sec() - tc;
            atomic_store(&w->progPpm, (uint64_t)((pass + 1) * 1e6 / K));
            if (stopRequested) return false;
        }
        if (!redo) break;
        K *= 2;                               /* too many groups in one pass */
        if (attempt > 20) die("cannot fit unit into group-id space");
    }
    reset_groups(w);
    *result = total;
    return true;
}

